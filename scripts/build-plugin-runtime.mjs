#!/usr/bin/env node
// Builds the Claude plugin's bundled CLI runtime into plugin/runtime/cli/, the tree
// plugin/runtime/muster.sh runs when the plugin is installed without a source checkout beside
// it. One `node` start replaces an `npx -y @adnova-group/muster@<version>` resolution on every
// CLI call (about 80 ms against 530 ms warm and 1.75 s cold).
//
//   plugin/runtime/cli/bin/muster.mjs            src/cli.js bundled with esbuild (yaml inlined)
//   plugin/runtime/cli/bin/verdict.schema.json   src/verdict.schema.json
//   plugin/runtime/cli/catalog/, pipelines/, vendor/manifest.yaml, package.json
//
// The bundle resolves its assets the way the source tree does, relative to its own
// import.meta.url (`../catalog/`, `../pipelines/`, `../vendor/manifest.yaml`, `../package.json`,
// `./verdict.schema.json`), so the generated tree mirrors the package layout one level down and
// src/ needs no asset-root seam.
//
// The tree is committed, so the plugin and its CLI always ship from the same commit. It must
// never go stale silently: `--check` rebuilds it in memory and fails on any byte that differs
// from the committed copy (test/plugin-runtime-bundle.test.js runs that check in `npm test`).
// After changing src/, catalog/, pipelines/, vendor/manifest.yaml or the package version, run
// `npm run build:plugin` and commit the result.
//
//   node scripts/build-plugin-runtime.mjs           write the tree
//   node scripts/build-plugin-runtime.mjs --check   exit 1 and list every stale path
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";
import { build, version as esbuildVersion } from "esbuild";

export const PLUGIN_RUNTIME_DIR = join("plugin", "runtime", "cli");
const ASSET_DIRS = ["catalog", "pipelines"];
const ASSET_FILES = [join("vendor", "manifest.yaml")];
const REQUIRE_BANNER = 'import { createRequire as __createRequire } from "node:module"; const require = __createRequire(import.meta.url);';

const posix = (path) => path.split(sep).join("/");
// Windows checkouts may convert text sources to CRLF; the generated tree is stored -text (LF).
const normalize = (bytes) => Buffer.from(bytes.toString("utf8").replace(/\r\n/g, "\n"));

function listFiles(root, dir) {
  const out = [];
  for (const entry of readdirSync(join(root, dir), { withFileTypes: true })) {
    const rel = join(dir, entry.name);
    if (entry.isDirectory()) out.push(...listFiles(root, rel));
    else if (entry.isFile()) out.push(rel);
  }
  return out.sort();
}

// Returns Map<posix path relative to plugin/runtime/cli, Buffer>: the complete generated tree.
export async function renderPluginRuntime(root) {
  const result = await build({
    absWorkingDir: root,
    entryPoints: ["src/cli.js"],
    outfile: join(PLUGIN_RUNTIME_DIR, "bin", "muster.mjs"),
    bundle: true,
    platform: "node",
    format: "esm",
    target: "node20",
    // Same externals as the Codex bundle (scripts/build-codex.mjs): the install-time Codex
    // generator path imports the build tooling and never runs from a bundled runtime.
    external: ["esbuild", "../scripts/build-codex.mjs"],
    banner: { js: REQUIRE_BANNER },
    legalComments: "none",
    metafile: true,
    write: false,
  });
  const files = new Map();
  for (const dir of ASSET_DIRS) {
    for (const rel of listFiles(root, dir)) files.set(posix(rel), normalize(readFileSync(join(root, rel))));
  }
  for (const rel of ASSET_FILES) files.set(posix(rel), normalize(readFileSync(join(root, rel))));
  files.set("bin/verdict.schema.json", normalize(readFileSync(join(root, "src", "verdict.schema.json"))));

  // The digest names every input that shaped the tree: each bundled module (from esbuild's own
  // metafile, so a new import is covered automatically), each asset, the package version and the
  // esbuild version.
  const version = JSON.parse(readFileSync(join(root, "package.json"), "utf8")).version;
  const hash = createHash("sha256").update(`muster.plugin-runtime.v1\0esbuild ${esbuildVersion}\0version ${version}\0`);
  for (const input of Object.keys(result.metafile.inputs).sort()) {
    hash.update(`m\0${posix(input)}\0`).update(normalize(readFileSync(join(root, input)))).update("\0");
  }
  for (const [rel, bytes] of [...files].sort(([a], [b]) => (a < b ? -1 : 1))) {
    hash.update(`a\0${rel}\0`).update(bytes).update("\0");
  }
  const sourceDigest = hash.digest("hex");

  let bundle = Buffer.from(result.outputFiles[0].contents).toString("utf8");
  const stamp = `// @adnova-group/muster ${version} plugin runtime, generated by scripts/build-plugin-runtime.mjs ` +
    `(sources sha256:${sourceDigest}). Do not edit: run \`npm run build:plugin\`.\n`;
  const shebang = bundle.startsWith("#!") ? bundle.slice(0, bundle.indexOf("\n") + 1) : "";
  bundle = shebang + stamp + bundle.slice(shebang.length);
  files.set("bin/muster.mjs", Buffer.from(bundle));
  files.set("package.json", Buffer.from(JSON.stringify({
    name: "@adnova-group/muster-plugin-runtime",
    private: true,
    version,
    sourceDigest,
    generatedBy: "scripts/build-plugin-runtime.mjs",
  }, null, 2) + "\n"));
  return new Map([...files].sort(([a], [b]) => (a < b ? -1 : 1)));
}

export async function writePluginRuntime(root) {
  const files = await renderPluginRuntime(root);
  const target = join(root, PLUGIN_RUNTIME_DIR);
  rmSync(target, { recursive: true, force: true });
  for (const [rel, bytes] of files) {
    mkdirSync(dirname(join(target, rel)), { recursive: true });
    writeFileSync(join(target, rel), bytes, { mode: rel === "bin/muster.mjs" ? 0o755 : 0o644 });
  }
  return { files: files.size, bytes: [...files.values()].reduce((sum, b) => sum + b.length, 0) };
}

// Compares the committed tree with a fresh in-memory build. `stale` lists every generated path
// whose bytes differ or that is missing, plus any committed file the build no longer produces.
export async function checkPluginRuntime(root) {
  const expected = await renderPluginRuntime(root);
  const target = join(root, PLUGIN_RUNTIME_DIR);
  const actual = existsSync(target) ? listFiles(target, "").map(posix) : [];
  const stale = [];
  for (const [rel, bytes] of expected) {
    const path = join(target, rel);
    if (!existsSync(path) || !normalize(readFileSync(path)).equals(bytes)) stale.push(rel);
  }
  for (const rel of actual) if (!expected.has(rel)) stale.push(rel);
  return { ok: stale.length === 0, stale: stale.sort() };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const root = fileURLToPath(new URL("../", import.meta.url));
  if (process.argv.includes("--check")) {
    const { ok, stale } = await checkPluginRuntime(root);
    if (!ok) {
      process.stderr.write(`${posix(PLUGIN_RUNTIME_DIR)} is stale (${stale.join(", ")}): run \`npm run build:plugin\` and commit the result.\n`);
      process.exitCode = 1;
    } else {
      process.stdout.write(`${posix(PLUGIN_RUNTIME_DIR)} matches its sources.\n`);
    }
  } else {
    const { files, bytes } = await writePluginRuntime(root);
    process.stdout.write(`Plugin runtime written to ${posix(relative(process.cwd(), join(root, PLUGIN_RUNTIME_DIR))) || "."} (${files} files, ${bytes} bytes)\n`);
  }
}
