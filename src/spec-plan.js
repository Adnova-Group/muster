// Planning from a SPEC.md (docs/strategy/2026-11-pm-domain-design.md "Plan integration",
// docs/plan-format.md "Planning from a spec", docs/spec-format.md).
//
// - specModel / specScope: the spec's IDs (spec-lint's parser and ID grammar), and which of
//   them a plan must deliver (`spec: path#REF-02` narrows the scope to one requirement).
// - lintSpecTraceability: plan-lint's `spec_traceability` dimension.
// - detectSpecRef / describeSpec: preflight's spec detection and readiness summary.
// - writeSpecContext: imports the spec's D-NN decisions (verbatim, LOCKED) and non-goals
//   (Deferred Ideas) into the run's CONTEXT.md, with the spec's path and sha256.
// - runSpecClarify: writes one question round's answers back into the spec under a dated
//   `## Clarifications` session, resolves the open questions and promotes a draft to ready.
//
// Spec and plan text are untrusted, LLM-authored markdown. Nothing here executes or shells out;
// reads are bounded and stay under the project root. No network.
//
// Module cycle: plan-lint -> spec-plan -> spec-lint -> plan-lint. It is safe only while no module
// in it reads an imported binding at load time, so keep imported names inside functions here.
import { createHash } from "node:crypto";
import { readFileSync, statSync } from "node:fs";
import { readFile } from "node:fs/promises";
import path from "node:path";
import { MAX_SPEC_BYTES, parseDocument, specReadiness } from "./spec-lint.js";
import { SEVERITY, withinRootLexical } from "./plan-lint.js";
import { writeContainedFile } from "./fs-safe.js";
import { assertRunId } from "./run-dir.js";

const DIMENSION = "spec_traceability";
// Kinds a task may cover or a verify command may prove; a requirement ID stands for its criteria.
const COVERABLE = new Set(["requirement", "ac", "invariant", "eval"]);
// Verify types an automated gate proves: uncovered = blocker.
const PROVEN = new Set(["test", "check", "eval"]);
const MARKER_FULL_RE = /\[NEEDS CLARIFICATION(?::\s*([^\]\n]*))?\]/g;
const MARKER_ANY_RE = /\[NEEDS CLARIFICATION/;
const LIST_ITEM_RE = /^\s*(?:[-*+]|\d+[.)])\s/;
const IMPORT_START = "<!-- muster:spec-import:start (generated by `muster spec-context`; edit the spec, not this block) -->";
const IMPORT_END = "<!-- muster:spec-import:end -->";
const IMPORT_BLOCK_RE = /<!-- muster:spec-import:start[^\n]*-->[\s\S]*?<!-- muster:spec-import:end -->/;

// ─── Spec reference and reading ──────────────────────────────────────────────

/** `docs/specs/x/SPEC.md#REF-02,REF-03` -> { path, anchors: ["REF-02", "REF-03"] }, or null. */
export function parseSpecRef(ref) {
  if (typeof ref !== "string" || !ref.trim()) return null;
  const [p, ...rest] = ref.trim().split("#");
  return { path: p.trim(), anchors: rest.join("#").split(/[\s,]+/).filter(Boolean) };
}

export function formatSpecRef(ref) {
  return ref.anchors.length ? `${ref.path}#${ref.anchors.join(",")}` : ref.path;
}

/** Read a spec under the project root. Returns { abs, text } or { error } (never throws). */
export function loadSpecFile(relPath, projectRoot) {
  const root = path.resolve(projectRoot);
  if (!relPath) return { error: "no path" };
  const abs = path.resolve(root, relPath);
  if (path.isAbsolute(relPath) || !withinRootLexical(abs, root)) return { error: "absolute or outside the project root" };
  try {
    const st = statSync(abs);
    if (!st.isFile()) return { error: "not a regular file" };
    if (st.size > MAX_SPEC_BYTES) return { error: `larger than ${MAX_SPEC_BYTES} bytes` };
    return { abs, text: readFileSync(abs, "utf8") };
  } catch (error) {
    return { error: error.code ?? error.message };
  }
}

export const sha256 = (text) => createHash("sha256").update(String(text), "utf8").digest("hex");

// ─── Spec model ──────────────────────────────────────────────────────────────

function verifyOf(text) {
  const all = [...String(text).matchAll(/\bverify:\s*([A-Za-z-]+)/gi)];
  return all.length === 1 ? all[0][1].toLowerCase() : null;
}

/** The raw source lines of a definition (its lead line plus list continuation lines). */
function rawDefinition(rawLines, doc, d) {
  const first = doc.lineOffset + d.line;
  const out = [rawLines[first] ?? ""];
  if (d.form === "list") {
    for (let j = first + 1; j < rawLines.length; j += 1) {
      const next = rawLines[j];
      if (!next.trim() || LIST_ITEM_RE.test(next) || /^\s*(?:#|\||```|~~~)/.test(next)) break;
      out.push(next);
    }
  }
  return out.map((l) => l.replace(/\s+$/, "")).join("\n").trim();
}

/**
 * The spec's IDs, in document order: requirements (with their criteria), criteria and
 * invariants (with their verify type), EV rows (verify `eval`), decisions and non-goals (with
 * their raw text), open questions (with blocks / resolved) and live clarification markers.
 * The first definition of a duplicated ID wins (spec-lint blocks the duplicate).
 */
export function specModel(rawText) {
  const doc = parseDocument(rawText);
  const rawLines = doc.text.split("\n");
  const byId = new Map();
  const order = [];
  for (const d of doc.definitions) {
    if (!d.cls || byId.has(d.token)) continue;
    const kind = d.cls.kind;
    if (kind === "requirement" && d.form !== "heading") continue;
    if (kind === "ac" && d.form !== "list") continue;
    const entry = { id: d.token, kind, line: d.line, text: d.text };
    if (kind === "requirement") entry.acs = [];
    else if (kind === "ac") { entry.requirement = d.cls.requirement; entry.verify = verifyOf(d.text); }
    else if (kind === "invariant") entry.verify = verifyOf(d.text);
    else if (kind === "eval") { entry.verify = "eval"; entry.text = d.form === "table" ? doc.lines[d.line] : d.text; }
    else if (kind === "decision" || kind === "non-goal") entry.raw = rawDefinition(rawLines, doc, d);
    else if (kind === "open question") {
      const blocks = /\bblocks?:\s*([^\n—]*)/i.exec(d.text);
      entry.resolved = /\bresolved\b/i.test(d.text) || /^~~/.test(d.text);
      entry.blocking = Boolean(blocks) && !entry.resolved && /\b(?:build|spec)\b/i.test(blocks[1]);
      entry.raw = rawDefinition(rawLines, doc, d);
    }
    byId.set(d.token, entry);
    order.push(entry);
  }
  for (const e of order) if (e.kind === "ac" && byId.get(e.requirement)?.kind === "requirement") byId.get(e.requirement).acs.push(e.id);
  const markers = [];
  doc.lines.forEach((line, i) => {
    const full = [...line.matchAll(MARKER_FULL_RE)];
    for (const m of full) markers.push({ line: i, column: m.index, length: m[0].length, question: (m[1] ?? "").trim() });
    // An unclosed marker still blocks readiness; it can be answered but not replaced in place.
    if (!full.length && MARKER_ANY_RE.test(line)) markers.push({ line: i, column: -1, length: 0, question: line.trim() });
  });
  const of = (kind) => order.filter((e) => e.kind === kind);
  const fm = doc.frontmatter;
  return {
    doc, byId, order, markers,
    status: fm && typeof fm.status === "string" ? fm.status.trim() : null,
    intent: fm && typeof fm.intent === "string" ? fm.intent : null,
    requirements: of("requirement"), acs: of("ac"), invariants: of("invariant"), evals: of("eval"),
    decisions: of("decision"), nonGoals: of("non-goal"), openQuestions: of("open question"),
  };
}

const mentions = (text, ids) => ids.some((id) => new RegExp(`(?<![A-Z0-9-])${id.replace(/\./g, "\\.")}(?![0-9])`).test(text));

/**
 * The IDs a plan must deliver. No anchor: every criterion, invariant and EV row. With anchors
 * (`#REF-02`, `#REF-02.1`, `#EV-01`): the anchored requirements' criteria, every invariant
 * (what must keep working is always in scope), the anchored EV rows and the EV rows that cite an
 * anchored requirement or criterion. Returns { items, unknown, anchored }.
 */
export function specScope(model, anchors = []) {
  const unknown = [];
  if (!anchors.length) return { items: [...model.acs, ...model.invariants, ...model.evals], unknown, anchored: false };
  const picked = new Set();
  const cited = [];
  for (const a of anchors) {
    const e = model.byId.get(a);
    if (!e || !COVERABLE.has(e.kind)) { unknown.push(a); continue; }
    cited.push(a);
    if (e.kind === "requirement") { e.acs.forEach((id) => picked.add(id)); }
    else picked.add(a);
  }
  for (const inv of model.invariants) picked.add(inv.id);
  for (const ev of model.evals) if (mentions(ev.text, cited)) picked.add(ev.id);
  return { items: model.order.filter((e) => picked.has(e.id)), unknown, anchored: true };
}

/** Which tasks cover and which verify commands prove each spec ID (requirement IDs expand). */
export function planCoverage(plan, model) {
  const expand = (id) => { const e = model.byId.get(id); return e?.kind === "requirement" ? e.acs : [id]; };
  const coveredBy = new Map();
  const provedBy = new Map();
  const humanVerified = new Map();
  const push = (map, id, who) => { const list = map.get(id) || []; if (!list.includes(who)) list.push(who); map.set(id, list); };
  for (const t of plan.tasks) {
    const who = t.id ?? `#${t.index}`;
    for (const c of t.covers) for (const id of expand(c)) {
      push(coveredBy, id, who);
      if (t.type === "checkpoint:human-verify") push(humanVerified, id, who);
    }
    for (const p of t.proves) for (const id of expand(p)) push(provedBy, id, who);
  }
  return { coveredBy, provedBy, humanVerified };
}

const listOf = (v) => (Array.isArray(v) ? v : v === undefined || v === null ? [] : [v]).flatMap((x) => String(x).split(/[\s,]+/)).filter(Boolean);

function mustHaves(fm, key) {
  const mh = fm && fm.must_haves && typeof fm.must_haves === "object" ? fm.must_haves : {};
  return Array.isArray(mh[key]) ? mh[key] : [];
}

/** Every spec ID the plan cites, with where it is cited. */
function citations(plan) {
  const out = [];
  const label = (t) => `task ${t.id ?? `#${t.index}`}`;
  for (const t of plan.tasks) {
    for (const id of t.covers) out.push({ id, where: `${label(t)} covers` });
    for (const id of t.proves) out.push({ id, where: `${label(t)} proves` });
  }
  const fm = plan.frontmatter || {};
  for (const id of listOf(fm.requirements)) out.push({ id, where: "frontmatter requirements" });
  for (const key of ["truths", "prohibitions"]) {
    mustHaves(fm, key).forEach((item, i) => {
      if (item && typeof item === "object") for (const id of listOf(item.ac)) out.push({ id, where: `must_haves.${key}[${i}] ac` });
    });
  }
  return out;
}

/** Is an invariant listed as a prohibition (by `ac:` or by its ID in the statement)? */
export function prohibited(plan, id) {
  return mustHaves(plan.frontmatter, "prohibitions").some((p) => {
    if (p && typeof p === "object") return listOf(p.ac).includes(id) || mentions(String(p.statement ?? ""), [id]);
    return mentions(String(p), [id]);
  });
}

const plural = (n, one, many) => (n === 1 ? one : many);

/**
 * plan-lint's spec_traceability dimension for a parsed plan whose frontmatter has `spec:`.
 * Severities follow the design table: a missing/unreadable or not-ready spec, an unknown ID and
 * an uncovered test/check/eval ID block; a judgment ID with no human-verify checkpoint, a covered
 * ID no verify command proves, an invariant missing from the prohibitions and a spec decision
 * missing from `decisions:` warn; needs-runtime IDs are info. Never throws.
 */
export function lintSpecTraceability(plan, { projectRoot = process.cwd() } = {}) {
  const issues = [];
  const add = (severity, required_property, summary) => issues.push({ dimension: DIMENSION, severity, required_property, summary });
  const fm = plan.frontmatter || {};
  const ref = parseSpecRef(fm.spec);
  if (!ref || !ref.path) {
    add(SEVERITY.BLOCKER, "`spec:` names the SPEC.md this plan builds (repo-relative, optional #REF-NN scope)", `spec is ${typeof fm.spec === "string" || fm.spec === null || fm.spec === undefined ? "empty" : `a ${Array.isArray(fm.spec) ? "list" : typeof fm.spec}, not a path`}`);
    return issues;
  }
  const loaded = loadSpecFile(ref.path, projectRoot);
  if (loaded.error) {
    add(SEVERITY.BLOCKER, "The plan's spec exists and is readable under the project root", `spec ${ref.path} cannot be read (${loaded.error})`);
    return issues;
  }
  const readiness = specReadiness(loaded.text, { projectRoot });
  if (!readiness.ready) {
    const why = [];
    if (readiness.status === null) why.push("it has no status");
    else if (!["ready", "in-build", "shipped"].includes(readiness.status)) why.push(`its status is ${readiness.status}`);
    if (readiness.blockers.length) why.push(`spec-lint reports ${readiness.blockers.length} ${plural(readiness.blockers.length, "blocker", "blockers")} (${readiness.blockers.slice(0, 3).map((b) => b.summary).join("; ")})`);
    const open = blockingQuestions(specModel(loaded.text)).map((q) => q.id);
    if (open.length) why.push(`${open.join(", ")} still ${plural(open.length, "blocks", "block")} build`);
    add(SEVERITY.BLOCKER, "The spec is ready: status ready or later, and no spec-lint blocker", `${ref.path} is not ready: ${why.join(", and ")}`);
  }
  const model = specModel(loaded.text);
  const scope = specScope(model, ref.anchors);
  for (const a of scope.unknown) add(SEVERITY.BLOCKER, "The spec scope (#…) names requirements, criteria, invariants or evals the spec defines", `scope #${a} is not a requirement, criterion, invariant or eval defined in ${ref.path}`);

  const unknown = new Map();
  for (const c of citations(plan)) {
    const e = model.byId.get(c.id);
    if (e && COVERABLE.has(e.kind)) continue;
    const entry = unknown.get(c.id) || { kind: e?.kind ?? null, where: [] };
    if (!entry.where.includes(c.where)) entry.where.push(c.where);
    unknown.set(c.id, entry);
  }
  for (const [id, { kind, where }] of unknown) {
    add(SEVERITY.BLOCKER, "Every covers, proves, requirements and ac ID is a requirement, criterion, invariant or eval the spec defines", `${id} (${where.join(", ")}) ${kind ? `is ${/^[aeiou]/.test(kind) ? "an" : "a"} ${kind} ID, which a task cannot cover` : `is not defined in ${ref.path}`}`);
  }

  const cov = planCoverage(plan, model);
  for (const e of scope.items) {
    if (PROVEN.has(e.verify) && !cov.coveredBy.has(e.id)) {
      add(SEVERITY.BLOCKER, "Every in-scope test, check and eval ID appears in some task's covers", `${e.id} (verify: ${e.verify}) is covered by no task`);
    }
  }
  for (const e of scope.items) {
    if (e.verify === "judgment" && !cov.humanVerified.has(e.id)) {
      add(SEVERITY.WARNING, "A judgment criterion is covered by a checkpoint:human-verify task", `${e.id} is verify: judgment but no checkpoint:human-verify task covers it`);
    }
  }
  for (const e of scope.items) {
    if (PROVEN.has(e.verify) && cov.coveredBy.has(e.id) && !cov.provedBy.has(e.id)) {
      add(SEVERITY.WARNING, "A covered test, check or eval ID is named by the <automated proves=\"…\"> command that proves it", `${e.id} is covered by task ${cov.coveredBy.get(e.id).join(", ")} but no <automated proves> names it`);
    }
  }
  for (const e of scope.items) {
    if (e.kind === "invariant" && !prohibited(plan, e.id)) {
      add(SEVERITY.WARNING, "Every invariant is a must_haves.prohibitions entry (ac: [INV-NN])", `${e.id} is not listed in must_haves.prohibitions`);
    }
  }
  const planned = new Set(listOf(fm.decisions));
  const missing = model.decisions.map((d) => d.id).filter((id) => !planned.has(id));
  if (missing.length) add(SEVERITY.WARNING, "Every spec decision D-NN is listed in the plan's decisions", `${missing.join(", ")} ${plural(missing.length, "is", "are")} decided in ${ref.path} but missing from decisions:`);
  const runtime = scope.items.filter((e) => e.verify === "needs-runtime").map((e) => e.id);
  if (runtime.length) add(SEVERITY.INFO, "A needs-runtime ID is proven by production data only", `${runtime.join(", ")} ${plural(runtime.length, "is", "are")} needs-runtime: the verifier records NEEDS-RUNTIME, never VERIFIED`);
  return issues;
}

// ─── Preflight: detection and readiness summary ──────────────────────────────

/**
 * The spec an outcome names: a backlog annotation `{spec: path#REF-02}` first, else the first
 * token that is a `…SPEC.md` path or a markdown file under `docs/specs/` (with an optional
 * `#anchor`). Returns the reference string or null.
 */
export function detectSpecRef(outcome) {
  const text = String(outcome ?? "");
  const note = /\{\s*spec:\s*([^}\s]+)\s*\}/i.exec(text);
  if (note) return note[1];
  for (const raw of text.split(/\s+/)) {
    const token = raw.replace(/^[("'`<[]+/, "").replace(/[)"'`>\],;:.!?]+$/, "");
    const file = token.split("#")[0];
    if (/(?:^|\/)SPEC\.md$/i.test(file) || /(?:^|\/)docs\/specs\/.+\.md$/i.test(file)) return token;
  }
  return null;
}

/** Questions for the one clarification round: blocking open questions, then live markers. */
export function blockingQuestions(model) {
  const qs = model.openQuestions.filter((q) => q.blocking).map((q) => ({ id: q.id, question: q.text.split(/\s+—\s+/)[0].trim() }));
  model.markers.forEach((m, i) => qs.push({ id: `NC-${i + 1}`, question: m.question || "[NEEDS CLARIFICATION] (no question text)" }));
  return qs;
}

/**
 * preflight's `spec` summary: { path, anchor, status, ready, acs, invariants, evals, decisions,
 * openQuestions: [{id, question}], blockers?, error? }. ID lists are the in-scope ones.
 */
export function describeSpec({ cwd, ref }) {
  const parsed = parseSpecRef(ref);
  const base = { path: parsed?.path ?? String(ref), anchor: parsed?.anchors.length ? parsed.anchors.join(",") : null };
  const loaded = loadSpecFile(parsed?.path, cwd);
  if (loaded.error) return { ...base, status: null, ready: false, acs: [], invariants: [], evals: [], decisions: [], openQuestions: [], error: `cannot read ${base.path}: ${loaded.error}` };
  const readiness = specReadiness(loaded.text, { projectRoot: cwd });
  const model = specModel(loaded.text);
  const scope = specScope(model, parsed.anchors);
  const ids = (kind) => scope.items.filter((e) => e.kind === kind).map((e) => e.id);
  return {
    ...base,
    status: readiness.status,
    ready: readiness.ready,
    acs: ids("ac"), invariants: ids("invariant"), evals: ids("eval"),
    decisions: model.decisions.map((d) => d.id),
    openQuestions: blockingQuestions(model),
    ...(readiness.blockers.length ? { blockers: readiness.blockers.slice(0, 5).map((b) => b.summary) } : {}),
    ...(scope.unknown.length ? { error: `scope #${scope.unknown.join(",")} names nothing the spec defines` } : {}),
  };
}

// ─── CONTEXT.md import ───────────────────────────────────────────────────────

function sectionLines(model, key) {
  const s = model.doc.sections.find((x) => x.key === key);
  return s ? model.doc.lines.slice(s.start, s.end) : [];
}

/** Non-goals: the Scope section's `Out:` items, the spec's NG definitions, and the linked
 * intent's definitions of every NG the spec references. Verbatim, deduplicated. */
function deferredIdeas(model, intentText) {
  const items = [];
  const fromIntent = new Map();
  if (intentText) {
    for (const ng of specModel(intentText).nonGoals) {
      if (mentions(model.doc.body, [ng.id])) fromIntent.set(ng.id, `${ng.raw.replace(/^\s*(?:[-*+]|\d+[.)])\s+/, "")} (from the intent)`);
    }
  }
  const scopeText = sectionLines(model, "scope").join("\n");
  const out = /\bOut:\s*([\s\S]*)$/i.exec(scopeText);
  if (out) {
    for (const seg of out[1].split(/;|\n/)) {
      const s = seg.trim();
      // A bare reference ("NG-01 (intent)") is replaced by the intent's own wording below.
      const bare = /^(NG-\d{2,3})\s*(?:\(intent\))?\.?$/.exec(s);
      if (s && !(bare && fromIntent.has(bare[1]))) items.push(s);
    }
  }
  for (const ng of model.nonGoals) items.push(ng.raw.replace(/^\s*(?:[-*+]|\d+[.)])\s+/, ""));
  items.push(...fromIntent.values());
  return [...new Set(items)];
}

export function renderSpecImport({ specPath, anchors, text, intentText }) {
  const model = specModel(text);
  const decisions = model.decisions.map((d) => d.raw);
  const deferred = deferredIdeas(model, intentText);
  return [
    IMPORT_START,
    "## Spec",
    "",
    `Source: \`${specPath}\` (sha256 \`${sha256(text)}\`)`,
    `Scope: ${anchors.length ? anchors.join(", ") : "every requirement"}. Status at import: ${model.status ?? "none"}.`,
    "",
    "## Decisions",
    "",
    decisions.length
      ? "LOCKED: imported verbatim from the spec. Changing one needs a new D-NN in the spec, not a plan edit."
      : "The spec records no decisions.",
    "",
    ...decisions,
    "",
    "## Deferred Ideas",
    "",
    deferred.length ? "The spec's non-goals. None of these may appear in the plan." : "The spec names no non-goals.",
    "",
    ...deferred.map((d) => `- ${d}`),
    IMPORT_END,
  ].join("\n").replace(/\n{3,}/g, "\n\n");
}

/** Insert or replace the generated import block, keeping everything else in CONTEXT.md. */
export function upsertSpecImport(existing, block, runId) {
  if (typeof existing !== "string" || !existing.trim()) return `# Run ${runId}: context\n\n${block}\n`;
  if (IMPORT_BLOCK_RE.test(existing)) return existing.replace(IMPORT_BLOCK_RE, () => block);
  return `${existing.replace(/\s*$/, "")}\n\n${block}\n`;
}

async function specRefFromPreflight(cwd, runId) {
  try {
    const detail = JSON.parse(await readFile(path.join(cwd, ".muster", "runs", runId, "preflight.json"), "utf8"));
    const s = detail && detail.spec;
    if (s && typeof s.path === "string") return s.anchor ? `${s.path}#${s.anchor}` : s.path;
  } catch { /* no preflight detail */ }
  return null;
}

/** `muster spec-context <runId> [--spec <path[#anchor]>]`. Returns a report; never throws on bad input. */
export async function writeSpecContext({ cwd, runId, specRef = null }) {
  try { assertRunId(runId); } catch (error) { return { ok: false, problems: [error.message] }; }
  const ref = parseSpecRef(specRef || (await specRefFromPreflight(cwd, runId)));
  if (!ref) return { ok: false, problems: ["no spec: pass --spec <path> or run preflight on an outcome that names one"] };
  const loaded = loadSpecFile(ref.path, cwd);
  if (loaded.error) return { ok: false, problems: [`cannot read spec ${ref.path}: ${loaded.error}`] };
  const model = specModel(loaded.text);
  const intent = model.intent && model.intent !== "inline" ? loadSpecFile(model.intent.split("#")[0].trim(), cwd) : null;
  const block = renderSpecImport({ specPath: ref.path, anchors: ref.anchors, text: loaded.text, intentText: intent?.text ?? null });
  const contextPath = path.join(cwd, ".muster", "runs", runId, "CONTEXT.md");
  let existing = null;
  try { existing = await readFile(contextPath, "utf8"); } catch { existing = null; }
  await writeContainedFile(cwd, contextPath, upsertSpecImport(existing, block, runId));
  return {
    ok: true,
    contextPath: path.relative(cwd, contextPath),
    spec: formatSpecRef(ref),
    sha256: sha256(loaded.text),
    decisions: model.decisions.map((d) => d.id),
    deferred: deferredIdeas(model, intent?.text ?? null).length,
  };
}

// ─── Clarifications ──────────────────────────────────────────────────────────

const FENCE_RE = /^\s*(?:```|~~~)/;

/** Raw line indexes of `## <title>` headings outside code fences. */
function headingIndex(lines, re) {
  let fence = false;
  for (let i = 0; i < lines.length; i += 1) {
    if (FENCE_RE.test(lines[i])) { fence = !fence; continue; }
    if (!fence && re.test(lines[i])) return i;
  }
  return -1;
}

function nextH2(lines, from) {
  let fence = false;
  for (let i = from; i < lines.length; i += 1) {
    if (FENCE_RE.test(lines[i])) { fence = !fence; continue; }
    if (!fence && /^##\s/.test(lines[i]) && !/^###/.test(lines[i])) return i;
  }
  return lines.length;
}

const oneLine = (s) => String(s ?? "").replace(/\s+/g, " ").trim();

/**
 * Apply one question round's answers ([{id, a, q?}]; ids from blockingQuestions) to a spec:
 * an OQ is marked resolved, an `NC-n` marker is replaced by its answer, and every answer is
 * recorded as `- Q: … → A: …` under `## Clarifications` / `### Session <date>`. Pure.
 */
export function applyClarifications(rawText, answers, { date }) {
  const model = specModel(rawText);
  const lines = model.doc.text.split("\n");
  const off = model.doc.lineOffset;
  const questions = new Map(blockingQuestions(model).map((q) => [q.id, q.question]));
  const applied = [];
  const unknown = [];
  const records = [];
  const markerEdits = [];
  for (const ans of Array.isArray(answers) ? answers : []) {
    const id = String(ans?.id ?? "").trim();
    const a = oneLine(ans?.a ?? ans?.answer);
    if (!id || !a) { unknown.push(id || "(no id)"); continue; }
    const q = oneLine(ans.q ?? ans.question ?? questions.get(id) ?? model.byId.get(id)?.text ?? id);
    const oq = model.byId.get(id);
    const nc = /^NC-(\d+)$/.exec(id);
    if (oq?.kind === "open question") {
      const at = off + oq.line;
      if (!oq.resolved) lines[at] = `${lines[at].replace(/\s+$/, "")} — resolved ${date}: see Clarifications`;
    } else if (nc && model.markers[Number(nc[1]) - 1]?.column >= 0) {
      markerEdits.push({ marker: model.markers[Number(nc[1]) - 1], a });
    } else { unknown.push(id); continue; }
    applied.push(id);
    records.push(`- Q: ${q} → A: ${a}`);
  }
  // Right to left within a line so earlier columns stay valid.
  markerEdits.sort((x, y) => y.marker.line - x.marker.line || y.marker.column - x.marker.column);
  for (const { marker, a } of markerEdits) {
    const at = off + marker.line;
    lines[at] = lines[at].slice(0, marker.column) + a + lines[at].slice(marker.column + marker.length);
  }
  const endsWithNewline = /\n$/.test(model.doc.text);
  if (records.length) {
    let c = headingIndex(lines, /^##\s+Clarifications\s*$/i);
    if (c < 0) {
      const trace = headingIndex(lines, /^##\s+Traceability\b/i);
      if (trace >= 0) { lines.splice(trace, 0, "## Clarifications"); c = trace; }
      else {
        while (lines.length && !lines[lines.length - 1].trim()) lines.pop();
        lines.push("", "## Clarifications");
        c = lines.length - 1;
      }
    }
    const end = nextH2(lines, c + 1);
    const content = lines.slice(c + 1, end);
    while (content.length && !content[content.length - 1].trim()) content.pop();
    const session = content.findIndex((l) => l.trim() === `### Session ${date}`);
    if (session < 0) content.push("", `### Session ${date}`, ...records);
    else {
      let at = session + 1;
      while (at < content.length && !/^#{2,3}\s/.test(content[at])) at += 1;
      while (at > session + 1 && !content[at - 1].trim()) at -= 1;
      content.splice(at, 0, ...records);
    }
    if (content[0] !== "") content.unshift("");
    if (end < lines.length) content.push("");
    lines.splice(c + 1, end - (c + 1), ...content);
  }
  let out = lines.join("\n");
  if (endsWithNewline && !out.endsWith("\n")) out += "\n";
  return { text: out, applied, unknown };
}

/** Promote `status: draft` to `ready` when the result would pass the readiness gate. */
export function promoteIfReady(rawText, { projectRoot }) {
  const now = specReadiness(rawText, { projectRoot });
  if (now.ready || now.status !== "draft") return { text: rawText, promoted: false, readiness: now };
  const fm = /^(﻿?---\n)([\s\S]*?)(\n---[ \t]*(?:\n|$))/.exec(rawText);
  if (!fm) return { text: rawText, promoted: false, readiness: now };
  const body = fm[2].replace(/^status:[ \t]*draft\b.*$/m, "status: ready");
  const candidate = rawText.slice(0, fm.index) + fm[1] + body + fm[3] + rawText.slice(fm.index + fm[0].length);
  const after = specReadiness(candidate, { projectRoot });
  return after.ready ? { text: candidate, promoted: true, readiness: after } : { text: rawText, promoted: false, readiness: now };
}

/**
 * `muster spec-clarify <SPEC.md> [--date YYYY-MM-DD]` with the answers as JSON on stdin
 * (`[{id, a, q?}]` or `{answers: [...]}`). Writes the spec once; returns a report whose `ready`
 * says whether planning can proceed.
 */
export async function runSpecClarify({ cwd, specPath, answers, date }) {
  const ref = parseSpecRef(specPath);
  const loaded = loadSpecFile(ref?.path, cwd);
  if (loaded.error) return { ok: false, problems: [`cannot read spec ${ref?.path ?? specPath}: ${loaded.error}`] };
  if (!/^\d{4}-\d{2}-\d{2}$/.test(date)) return { ok: false, problems: [`--date must be YYYY-MM-DD, got ${date}`] };
  const crlf = /\r\n/.test(loaded.text);
  const { text, applied, unknown } = applyClarifications(loaded.text, answers, { date });
  const promoted = promoteIfReady(text, { projectRoot: cwd });
  const final = crlf ? promoted.text.replace(/\n/g, "\r\n") : promoted.text;
  if (final !== loaded.text) await writeContainedFile(cwd, loaded.abs, final);
  const r = promoted.readiness;
  return {
    ok: unknown.length === 0,
    path: ref.path,
    applied,
    ...(unknown.length ? { unknown } : {}),
    status: r.status,
    ready: r.ready,
    promoted: promoted.promoted,
    ...(r.blockers.length ? { blockers: r.blockers.map((b) => b.summary) } : {}),
    remaining: blockingQuestions(specModel(promoted.text)).map((q) => q.id),
  };
}
