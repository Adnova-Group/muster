// `muster spec-trace <runId> [--accept <IDs>] [--coverage] [--json]`: close the loop from a run
// back to its SPEC.md (docs/strategy/2026-11-pm-domain-design.md "Plan integration").
//
// After verification it regenerates the spec's `## Traceability` block from PLAN.md (`covers`,
// `<automated proves>`) and VERIFICATION.md (the verifier's `## Acceptance` table), and sets
// `status: shipped` once every criterion, invariant and EV row of the spec is VERIFIED or
// explicitly accepted (`--accept`, or ACCEPTED in the Acceptance table). Rows of IDs outside
// this run's scope are kept, so a spec built requirement by requirement accumulates its table.
// `--coverage` writes nothing: one line per requirement for /muster:plan's approval stop.
//
// PLAN.md, VERIFICATION.md and the spec are untrusted text. Nothing here executes; reads are
// bounded; the only write is the spec, under the project root.
import { readFileSync, statSync } from "node:fs";
import path from "node:path";
import { MAX_PLAN_BYTES, parsePlan } from "./plan-lint.js";
import { splitRow } from "./spec-lint.js";
import { formatSpecRef, loadSpecFile, parseSpecRef, planCoverage, prohibited, specModel, specScope } from "./spec-plan.js";
import { writeContainedFile } from "./fs-safe.js";
import { assertRunId } from "./run-dir.js";

export const ACCEPTANCE_STATUSES = Object.freeze(["VERIFIED", "FAILED", "NEEDS-HUMAN", "NEEDS-RUNTIME", "ORPHANED", "ACCEPTED"]);
const STATUS_RE = /(?<![A-Z-])(NEEDS-HUMAN|NEEDS-RUNTIME|VERIFIED|FAILED|ORPHANED|ACCEPTED)(?![A-Z-])/;
const DONE = new Set(["VERIFIED", "ACCEPTED"]);
const PROVEN = new Set(["test", "check", "eval"]);
const FENCE_RE = /^\s*(?:```|~~~)/;
const TRACE_COMMENT = "<!-- generated by `muster spec-trace`; do not edit -->";
const TRACE_HEADER = ["| ID | Tasks | Verify | Status | Run |", "|---|---|---|---|---|"];

function readBounded(file, max) {
  const st = statSync(file);
  if (!st.isFile()) throw Object.assign(new Error("not a regular file"), { code: "ENOTFILE" });
  if (st.size > max) throw Object.assign(new Error(`larger than ${max} bytes`), { code: "EFBIG" });
  return readFileSync(file, "utf8");
}

/** [start, end) of the `## <title>` section in lines (fences skipped), or null. */
function sectionRange(lines, titleRe) {
  let fence = false;
  let start = -1;
  for (let i = 0; i < lines.length; i += 1) {
    if (FENCE_RE.test(lines[i])) { fence = !fence; continue; }
    if (fence || !/^##\s/.test(lines[i]) || /^###/.test(lines[i])) continue;
    if (start >= 0) return [start, i];
    if (titleRe.test(lines[i])) start = i;
  }
  return start >= 0 ? [start, lines.length] : null;
}

const cleanId = (cell) => String(cell ?? "").replace(/[*`]/g, "").trim();

/** The verifier's `## Acceptance` table: Map id -> { status, evidence }. */
export function parseAcceptance(text) {
  const lines = String(text ?? "").replace(/\r\n/g, "\n").split("\n");
  const range = sectionRange(lines, /^##\s+Acceptance\b/i);
  const out = new Map();
  if (!range) return out;
  const rows = lines.slice(range[0] + 1, range[1]).filter((l) => /^\s*\|/.test(l));
  if (!rows.length) return out;
  const header = splitRow(rows[0]).map((h) => h.toLowerCase());
  const idCol = Math.max(0, header.findIndex((h) => /^id$/.test(cleanId(h))));
  const statusCol = header.findIndex((h) => /status/.test(h));
  const evidenceCol = header.findIndex((h) => /evidence/.test(h));
  for (const row of rows.slice(1)) {
    if (/^\s*\|?\s*:?-{3,}/.test(row)) continue;
    const cells = splitRow(row);
    const id = cleanId(cells[idCol]);
    const m = STATUS_RE.exec(String(statusCol >= 0 ? cells[statusCol] : row).toUpperCase());
    if (id && m && !out.has(id)) out.set(id, { status: m[1], evidence: evidenceCol >= 0 ? cells[evidenceCol] ?? "" : "" });
  }
  return out;
}

const escapeCell = (s) => String(s).replace(/\|/g, "\\|").replace(/\s+/g, " ").trim();

/** One Traceability row per in-scope ID. */
export function traceRows({ model, scope, cov, acceptance, accept, runId }) {
  return scope.items.map((e) => {
    const tasks = cov.coveredBy.get(e.id) || [];
    const proved = cov.provedBy.get(e.id) || [];
    let status;
    if (accept.has(e.id)) status = "ACCEPTED";
    else if (acceptance.has(e.id)) status = acceptance.get(e.id).status;
    else if (e.verify === "needs-runtime") status = "NEEDS-RUNTIME";
    else if (!tasks.length) status = "ORPHANED";
    else if (e.verify === "judgment") status = "NEEDS-HUMAN";
    else status = "UNVERIFIED";
    const verify = `${e.verify ?? "?"}${proved.length ? ` (proved by ${proved.join(", ")})` : ""}`;
    return { id: e.id, tasks, verify, status, run: runId, line: `| ${e.id} | ${tasks.join(", ") || "—"} | ${escapeCell(verify)} | ${status} | ${escapeCell(runId)} |` };
  });
}

/** Rows of the current Traceability table: Map id -> { status, line }. */
function existingRows(lines) {
  const range = sectionRange(lines, /^##\s+Traceability\b/i);
  const out = new Map();
  if (!range) return out;
  for (const l of lines.slice(range[0] + 1, range[1])) {
    if (!/^\s*\|/.test(l)) continue;
    const cells = splitRow(l);
    const id = cleanId(cells[0]);
    if (!/^[A-Z][A-Z0-9]*-\d/.test(id)) continue;
    const m = STATUS_RE.exec(String(cells[3] ?? "").toUpperCase());
    out.set(id, { status: m ? m[1] : "UNVERIFIED", line: l.trim() });
  }
  return out;
}

/**
 * Rewrite the spec text: the Traceability block (this run's rows replace theirs, other rows
 * stay, ordered as the spec defines them) and, when every criterion, invariant and EV row is
 * VERIFIED or ACCEPTED, `status: shipped`. Pure. Returns { text, merged, shipped }.
 */
export function rewriteSpec(rawText, { model, rows }) {
  const text = String(rawText).replace(/\r\n/g, "\n");
  const lines = text.split("\n");
  const merged = existingRows(lines);
  for (const [id] of merged) if (!model.byId.has(id)) merged.delete(id);
  for (const r of rows) merged.set(r.id, { status: r.status, line: r.line });
  const rank = new Map(model.order.map((e, i) => [e.id, i]));
  const ordered = [...merged.entries()].sort((a, b) => (rank.get(a[0]) ?? 1e9) - (rank.get(b[0]) ?? 1e9));
  const block = ["## Traceability", TRACE_COMMENT, ...TRACE_HEADER, ...ordered.map(([, r]) => r.line)];
  const range = sectionRange(lines, /^##\s+Traceability\b/i);
  if (range) {
    const tail = range[1] < lines.length ? [""] : (text.endsWith("\n") ? [""] : []);
    lines.splice(range[0], range[1] - range[0], ...block, ...tail);
  } else {
    while (lines.length && !lines[lines.length - 1].trim()) lines.pop();
    lines.push("", ...block, "");
  }
  let out = lines.join("\n");
  const verifiable = [...model.acs, ...model.invariants, ...model.evals];
  const shipped = verifiable.length > 0 && verifiable.every((e) => DONE.has(merged.get(e.id)?.status));
  if (shipped && ["ready", "in-build"].includes(model.status)) {
    out = out.replace(/^(﻿?---\n[\s\S]*?)^status:[ \t]*\S+.*$/m, "$1status: shipped");
  }
  return { text: out, merged, shipped };
}

/** One coverage line per requirement (then one per invariant and EV row) for the approval stop. */
export function coverageLines({ model, scope, cov, plan }) {
  const inScope = new Set(scope.items.map((e) => e.id));
  const lines = [];
  const who = (id) => (cov.coveredBy.get(id) || []).join(",");
  for (const r of model.requirements) {
    const acs = r.acs.filter((id) => inScope.has(id)).map((id) => model.byId.get(id));
    if (!acs.length) continue;
    const covered = acs.filter((e) => cov.coveredBy.has(e.id)).length;
    const provable = acs.filter((e) => PROVEN.has(e.verify));
    const proved = provable.filter((e) => cov.provedBy.has(e.id)).length;
    const parts = acs.map((e) => {
      const suffix = e.id.slice(r.id.length);
      if (e.verify === "needs-runtime") return `${suffix} needs-runtime`;
      if (!cov.coveredBy.has(e.id)) return `${suffix}→UNCOVERED`;
      const note = e.verify === "judgment" ? (cov.humanVerified.has(e.id) ? " human-verify" : " no checkpoint") : (cov.provedBy.has(e.id) ? "" : " no proves");
      return `${suffix}→${who(e.id)}${note}`;
    });
    lines.push(`${r.id}: covered ${covered}/${acs.length}, proved ${proved}/${provable.length} · ${parts.join(" ")}`);
  }
  for (const e of scope.items.filter((x) => x.kind === "invariant")) {
    lines.push(`${e.id}: ${cov.coveredBy.has(e.id) ? `covered by ${who(e.id)}` : "UNCOVERED"} · prohibition ${prohibited(plan, e.id) ? "yes" : "MISSING"} · ${cov.provedBy.has(e.id) ? "proved" : "no proves"}`);
  }
  for (const e of scope.items.filter((x) => x.kind === "eval")) {
    lines.push(`${e.id}: ${cov.coveredBy.has(e.id) ? `covered by ${who(e.id)}` : "UNCOVERED"} · ${cov.provedBy.has(e.id) ? `eval command in ${(cov.provedBy.get(e.id) || []).join(",")}` : "no eval command"}`);
  }
  return lines;
}

/** Load PLAN.md and its spec for a run. Returns { plan, ref, spec, model, scope, cov } or { problems }. */
function loadRun(cwd, runId) {
  try { assertRunId(runId); } catch (error) { return { problems: [error.message] }; }
  const dir = path.join(cwd, ".muster", "runs", runId);
  let planText;
  try { planText = readBounded(path.join(dir, "PLAN.md"), MAX_PLAN_BYTES); } catch (error) { return { problems: [`cannot read .muster/runs/${runId}/PLAN.md: ${error.code ?? error.message}`] }; }
  const plan = parsePlan(planText);
  const ref = parseSpecRef(plan.frontmatter?.spec);
  if (!ref || !ref.path) return { problems: ["PLAN.md names no spec (frontmatter spec:); spec-trace applies to runs planned from a SPEC.md"] };
  const spec = loadSpecFile(ref.path, cwd);
  if (spec.error) return { problems: [`cannot read spec ${ref.path}: ${spec.error}`] };
  const model = specModel(spec.text);
  const scope = specScope(model, ref.anchors);
  if (scope.unknown.length) return { problems: [`spec scope #${scope.unknown.join(",")} names nothing ${ref.path} defines`] };
  return { dir, plan, ref, spec, model, scope, cov: planCoverage(plan, model) };
}

export async function runSpecTrace({ cwd, runId, accept = [], coverage = false }) {
  const run = loadRun(cwd, runId);
  if (run.problems) return { ok: false, runId, problems: run.problems };
  const { dir, plan, ref, spec, model, scope, cov } = run;
  if (coverage) return { ok: true, runId, spec: formatSpecRef(ref), coverage: coverageLines({ model, scope, cov, plan }) };
  let verification;
  try { verification = readBounded(path.join(dir, "VERIFICATION.md"), MAX_PLAN_BYTES); } catch (error) {
    return { ok: false, runId, problems: [`cannot read .muster/runs/${runId}/VERIFICATION.md (${error.code ?? error.message}): run spec-trace after verification`] };
  }
  const acceptSet = new Set(accept);
  const inScope = new Set(scope.items.map((e) => e.id));
  const strays = accept.filter((id) => !inScope.has(id));
  if (strays.length) return { ok: false, runId, problems: [`--accept ${strays.join(", ")}: not in this run's scope of ${ref.path}`] };
  const rows = traceRows({ model, scope, cov, acceptance: parseAcceptance(verification), accept: acceptSet, runId });
  const crlf = /\r\n/.test(spec.text);
  const { text, merged, shipped } = rewriteSpec(spec.text, { model, rows });
  const final = crlf ? text.replace(/\n/g, "\r\n") : text;
  if (final !== spec.text) await writeContainedFile(cwd, spec.abs, final);
  const counts = {};
  for (const r of rows) counts[r.status] = (counts[r.status] ?? 0) + 1;
  const after = specModel(text).status;
  return {
    ok: true,
    runId,
    spec: formatSpecRef(ref),
    counts,
    shipped,
    status: after,
    open: [...merged.entries()].filter(([, r]) => !DONE.has(r.status)).map(([id, r]) => `${id} ${r.status}`),
    rows: rows.map(({ id, tasks, verify, status }) => ({ id, tasks, verify, status })),
  };
}

export function formatSpecTrace(report) {
  if (!report.ok) return `spec-trace ${report.runId ?? ""}: not written\n${report.problems.map((p) => `  ${p}`).join("\n")}`;
  if (report.coverage) return [`coverage ${report.spec}`, ...report.coverage.map((l) => `  ${l}`)].join("\n");
  const counts = Object.entries(report.counts).map(([k, v]) => `${v} ${k}`).join(", ") || "no in-scope IDs";
  const tail = report.shipped ? `status ${report.status}` : `status stays ${report.status} (not every ID is VERIFIED or accepted)`;
  return [`spec-trace ${report.runId}: ${report.spec}: ${counts}; ${tail}`, ...report.open.map((o) => `  open: ${o}`)].join("\n");
}

/** CLI entry. Returns the exit code: 0 written (or coverage printed), 1 not written, 2 usage. */
export async function runSpecTraceCli(args, io = {}) {
  const stdout = io.stdout ?? process.stdout;
  const stderr = io.stderr ?? process.stderr;
  const cwd = io.cwd ?? process.cwd();
  const usage = "usage: muster spec-trace <runId> [--accept <ID,...>] [--coverage] [--json]";
  let json = false;
  let coverage = false;
  const accept = [];
  const positionals = [];
  for (let i = 0; i < args.length; i += 1) {
    const a = args[i];
    if (a === "--json") json = true;
    else if (a === "--coverage") coverage = true;
    else if (a === "--accept") {
      const v = args[i + 1];
      i += 1;
      if (!v) { stderr.write(`muster: spec-trace: --accept needs IDs\n${usage}\n`); return 2; }
      accept.push(...v.split(/[\s,]+/).filter(Boolean));
    } else if (a.startsWith("--")) { stderr.write(`muster: spec-trace: unknown flag ${a}\n${usage}\n`); return 2; }
    else positionals.push(a);
  }
  if (positionals.length !== 1) { stderr.write(`muster: spec-trace: expected one runId\n${usage}\n`); return 2; }
  const report = await runSpecTrace({ cwd, runId: positionals[0], accept, coverage });
  stdout.write(`${json ? JSON.stringify(report, null, 2) : formatSpecTrace(report)}\n`);
  return report.ok ? 0 : 1;
}
